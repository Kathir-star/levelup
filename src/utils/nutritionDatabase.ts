export function calculateMacroTargets(profile: UserProfile | null, settings?: Partial<AppSettings>) {
  const weight = profile?.weight || 70;
  const height = profile?.height || 175;
  const age = profile?.age || 24;
  const gender = profile?.gender || 'male';
  const goal = profile?.goal || 'Muscle Gain';
  const activity = profile?.activityLevel || 'Moderately Active';

  // Mifflin-St Jeor BMR
  const bmr = Math.round(
    10 * weight + 6.25 * height - 5 * age + (gender === 'male' ? 5 : -161)
  );

  const activityMultipliers: Record<string, number> = {
    'Sedentary': 1.2,
    'Lightly Active': 1.375,
    'Moderately Active': 1.55,
    'Very Active': 1.725,
    'Athlete': 1.9
  };

  const tdee = Math.round(bmr * (activityMultipliers[activity] || 1.55));

  let targetCalories = tdee;
  if (goal === 'Muscle Gain') targetCalories = tdee + 300;
  else if (goal === 'Fat Loss') targetCalories = Math.max(1400, tdee - 450);
  else if (goal === 'Body Recomposition') targetCalories = tdee - 150;
  else if (goal === 'Athletic Performance') targetCalories = tdee + 200;

  // Protein: 2.0g/kg for muscle gain/recomp/fat loss, 1.8g/kg maintenance
  let targetProtein = Math.round(weight * (goal === 'Maintenance' ? 1.8 : 2.1));
  let targetFats = Math.round((targetCalories * 0.25) / 9);
  let targetCarbs = Math.max(80, Math.round((targetCalories - targetProtein * 4 - targetFats * 9) / 4));

  if (settings?.calorieTarget && settings.calorieTarget > 800) {
    targetCalories = settings.calorieTarget;
  }
  if (settings?.proteinTarget && settings.proteinTarget > 30) {
    targetProtein = settings.proteinTarget;
  }
  if (settings?.fatsTarget && settings.fatsTarget > 15) {
    targetFats = settings.fatsTarget;
  }
  if (settings?.carbsTarget && settings.carbsTarget > 30) {
    targetCarbs = settings.carbsTarget;
  }

  return {
    bmr,
    tdee,
    calories: targetCalories,
    protein: targetProtein,
    carbs: targetCarbs,
    fats: targetFats,
    fiber: settings?.fiberTarget || 30
  };
}

